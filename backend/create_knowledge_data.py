def create_article_comments():
    """创建文章评论"""
    print("\n" + "="*60)
    print("正在创建文章评论...")
    print("="*60)

    db = SessionLocal()
    try:
        # 获取普通用户
        users = db.query(User).filter(User.role == "user").all()
        # 获取已发布的文章
        articles = db.query(KnowledgeArticle).filter(
            KnowledgeArticle.status == "published"
        ).all()

        if not users or not articles:
            print("Users or articles not enough, skipping")
            return True

        comment_templates = [
            "这篇文章写得太好了，对我很有帮助！",
            "感谢分享，学到了很多实用技巧。",
            "我也有类似的困扰，按照文章中的方法试试。",
            "很有深度的文章，值得反复阅读。",
            "希望能看到更多这样高质量的内容。",
            "文章提到的方法我试过了，确实有效！",
            "这个话题很重要，希望能有更多探讨。"
        ]

        created_count = 0
        for article in articles:
            # 为每篇文章添加2-5条评论
            num_comments = random.randint(2, 5)
            for _ in range(num_comments):
                user = random.choice(users)

                # 检查是否已存在评论
                existing = db.query(KnowledgeComment).filter(
                    KnowledgeComment.article_id == article.id,
                    KnowledgeComment.user_id == user.id
                ).first()

                if not existing:
                    comment = KnowledgeComment(
                        article_id=article.id,
                        user_id=user.id,
                        content=random.choice(comment_templates),
                        created_at=datetime.now() - timedelta(days=random.randint(1, 30))
                    )
                    db.add(comment)
                    created_count += 1

        # 更新文章评论数
        for article in articles:
            comment_count = db.query(KnowledgeComment).filter(
                KnowledgeComment.article_id == article.id
            ).count()
            article.comment_count = comment_count

        db.commit()
        print(f"[SUCCESS] Created {created_count} comments")
        return True

    except Exception as e:
        print(f"[ERROR] Failed to create comments: {e}")
        db.rollback()
        return False
    finally:
        db.close()


def create_article_likes_and_favorites():
    """创建文章点赞和收藏"""
    print("\n" + "="*60)
    print("正在创建文章点赞和收藏...")
    print("="*60)

    db = SessionLocal()
    try:
        users = db.query(User).filter(User.role == "user").all()
        articles = db.query(KnowledgeArticle).filter(
            KnowledgeArticle.status == "published"
        ).all()

        if not users or not articles:
            print("Users or articles not enough, skipping")
            return True

        created_likes = 0
        created_favorites = 0

        for user in users:
            for article in articles:
                # 随机决定是否点赞和收藏
                if random.random() > 0.6:  # 40% 概率点赞
                    existing_like = db.query(KnowledgeLike).filter(
                        KnowledgeLike.article_id == article.id,
                        KnowledgeLike.user_id == user.id
                    ).first()

                    if not existing_like:
                        like = KnowledgeLike(
                            article_id=article.id,
                            user_id=user.id,
                            created_at=datetime.now() - timedelta(days=random.randint(1, 60))
                        )
                        db.add(like)
                        created_likes += 1

                if random.random() > 0.8:  # 20% 概率收藏
                    existing_fav = db.query(KnowledgeFavorite).filter(
                        KnowledgeFavorite.article_id == article.id,
                        KnowledgeFavorite.user_id == user.id
                    ).first()

                    if not existing_fav:
                        favorite = KnowledgeFavorite(
                            article_id=article.id,
                            user_id=user.id,
                            created_at=datetime.now() - timedelta(days=random.randint(1, 60))
                        )
                        db.add(favorite)
                        created_favorites += 1

        # 更新文章的点赞数和收藏数
        for article in articles:
            like_count = db.query(KnowledgeLike).filter(
                KnowledgeLike.article_id == article.id
            ).count()
            favorite_count = db.query(KnowledgeFavorite).filter(
                KnowledgeFavorite.article_id == article.id
            ).count()
            article.like_count = like_count
            article.favorite_count = favorite_count

        db.commit()
        print(f"[SUCCESS] Created {created_likes} likes and {created_favorites} favorites")
        return True

    except Exception as e:
        print(f"[ERROR] Failed to create likes and favorites: {e}")
        db.rollback()
        return False
    finally:
        db.close()


